Work Phishing Awareness Simulation
About This Project
This project is an educational demonstration designed to teach users how phishing attacks work and how to recognize suspicious Gmail-related websites.
The project provides a simulated phishing-awareness experience for cybersecurity education.
Project Objectives
• Demonstrate common phishing techniques.
• Help users recognize suspicious login pages.
• Promote safe internet browsing habits.
• Improve cybersecurity awareness.
Features
• Simple and responsive user interface.
• Educational phishing-awareness demonstration.
• Warning messages explaining potential security risks.
• No collection or storage of real Gmail passwords or credentials.
Technologies Used
• HTML
• CSS
• JavaScript
How to Run
1. Download or clone this repository.
2. Open the project folder.
3. Locate the index.html file.
4. Open it in your web browser.
Security Notice
This project is strictly for educational and authorized cybersecurity awareness purposes. It does not impersonate Google’s live login service or collect real user credentials.
